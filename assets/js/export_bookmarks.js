/*
  The code is generated by Claude Sonnet 3.5

  Session object format:
  { title: "Session title", presenters: "Presenter A, Presenter B" }
*/

// Configuration
const CANVAS_WIDTH = 600;
const PADDING = 28;
const GAP_BETWEEN_RECTS = 20; // horizontal gap between 2 rects in a row
const VERTICAL_GAP_BETWEEN_ROWS = 18;
const RECT_PADDING_X = 16; // horizontal inner padding of rectangle
const RECT_PADDING_Y = 12; // vertical inner padding of rectangle
const BACKGROUND_COLOR = '#1556F0';

// Header / logo sizes
const LOGO_WIDTH = 337;
const LOGO_HEIGHT = 135;
const HEADER_FONT = '700 32px "Arial"';
const HEADER_COLOR = '#ffffff';
const HEADER_RIGHT_SPACE = 12; // space between header and logo area

// Text font size ranges
const TITLE_BASE_SIZE = 18; // starting title size in px
const TITLE_MIN_SIZE = 12;
const PRES_BASE_SIZE = 14;
const PRES_MIN_SIZE = 10;
const MAX_LINES_TITLE = 5; // max lines for title
const MAX_LINES_PRESENTERS = 3; // max lines for presenters

// Rounded rect radius
const RECT_RADIUS = 12;

// Theme of the app (e.g. limmud2026.css defines --brand-gradient): dark background, brand stripe and
// the navbar logo. Without such a theme the original look (blue + bookmarks_logo.png) is kept.
function exportTheme() {
  const css = getComputedStyle(document.documentElement);
  const v = (name) => css.getPropertyValue(name).trim();
  if (!v('--brand-gradient')) {
    return { themed: false, background: BACKGROUND_COLOR, logoSrc: 'assets/img/bookmarks_logo.png',
             logoWidth: LOGO_WIDTH, logoHeight: LOGO_HEIGHT };
  }
  const navLogo = document.querySelector('img.logo');
  return {
    themed: true,
    background: v('--background-color') || '#1b1446',
    // the START page poster (festival name, dates, place) as the banner on top
    logoSrc: 'assets/img/poster_' + (((navLogo && navLogo.getAttribute('alt')) || document.title || '').match(/\d{4}/) || [''])[0] + '_desktop.png',
    stripe: ['#654ADC', v('--brand-pink') || '#F324D4', v('--brand-orange') || '#FD7A31'],
    festival: (navLogo && navLogo.getAttribute('alt')) || document.title || '',
    logoWidth: null    // banner: full width, height from the image proportions
  };
}

async function generateJPEG(bookmarkedSessions) {
  const theme = exportTheme();
  // Load logo image
  const logo = await loadImage(theme.logoSrc).catch((err) => {
    console.warn('Failed to load logo image:', err);
    return null;
  });
  // themed: the poster banner across the top (0 if it could not be loaded - then the festival name is written instead)
  const bannerHeight = (theme.themed && logo) ? Math.round(CANVAS_WIDTH * logo.naturalHeight / logo.naturalWidth) : 0;

  // create a temporary context to measure text (off-screen canvas)
  const measureCanvas = document.createElement('canvas');
  measureCanvas.width = 1; measureCanvas.height = 1;
  const mctx = measureCanvas.getContext('2d');

  // compute header height area
  mctx.font = HEADER_FONT;
  const headerHeight = 48; // approximate (font uses 32px plus spacing)
  const headerTopArea = theme.themed
    ? bannerHeight + 20 + headerHeight + (bannerHeight ? 0 : 30) + 4 - PADDING   // banner + header (+ festival name) + gap
    : Math.max(headerHeight, (logo ? LOGO_HEIGHT : 0)); // no extra gap

  // available width for a row (between left padding and right padding)
  const availableRowWidth = CANVAS_WIDTH - 2 * PADDING;

  // For each session compute minimal rectangle width and height needed
  // We'll search for minimal width that fits both title and presenters within allowed lines,
  // decreasing font if needed (bounded by min sizes).
  const sessionBoxes = bookmarkedSessions.map(sess => {
    const box = computeBoxSizeForSession(mctx, sess, availableRowWidth);
    return { ...box, data: sess };
  });

  // Now layout them two per row, adjusting widths so they fit in the same row
  const rows = [];
  for (let i = 0; i < sessionBoxes.length; i += 2) {
    const a = sessionBoxes[i];
    const b = sessionBoxes[i + 1] || null;

    if (!b) {
      // single item row: expand to full available width
      const width = availableRowWidth;
      const expanded = computeBoxSizeForSession(mctx, a.data, availableRowWidth, width);
      rows.push([{ ...expanded, width }, null]);
    } else {
      // two items: adjust widths proportionally to fill the row
      let w1 = a.width;
      let w2 = b.width;
      const MIN_RECT_WIDTH = 140;

      // Calculate the total space available for both boxes
      const totalAvailableWidth = availableRowWidth - GAP_BETWEEN_RECTS;

      // Calculate proportions based on their minimal widths
      const totalMinWidth = w1 + w2;
      const ratio1 = w1 / totalMinWidth;
      const ratio2 = w2 / totalMinWidth;

      // Expand or shrink proportionally to fill the row
      w1 = Math.max(MIN_RECT_WIDTH, Math.round(totalAvailableWidth * ratio1));
      w2 = Math.max(MIN_RECT_WIDTH, Math.round(totalAvailableWidth * ratio2));

      // Adjust for rounding errors to ensure exact fit
      const diff = totalAvailableWidth - (w1 + w2);
      if (diff !== 0) {
        // Add the difference to the larger box
        if (w1 >= w2) {
          w1 += diff;
        } else {
          w2 += diff;
        }
      }

      // recompute heights for adjusted widths (since wrapping may change)
      const newA = computeBoxSizeForSession(mctx, a.data, availableRowWidth, w1);
      const newB = computeBoxSizeForSession(mctx, b.data, availableRowWidth, w2);
      rows.push([ { ...newA, width: w1 }, { ...newB, width: w2 } ]);
    }
  }

  // compute canvas height
  let y = PADDING + headerTopArea;
  for (const row of rows) {
    const a = row[0];
    const b = row[1];
    const rowH = Math.max(a.height, b ? b.height : 0);
    y += rowH + VERTICAL_GAP_BETWEEN_ROWS;
  }
  y += PADDING - VERTICAL_GAP_BETWEEN_ROWS; // bottom padding adjustment
  const canvasHeight = Math.max(y, headerTopArea + 2 * PADDING);

  // create final canvas
  const canvas = document.createElement('canvas');
  canvas.width = CANVAS_WIDTH;
  canvas.height = canvasHeight;
  const ctx = canvas.getContext('2d');

  // draw background
  ctx.fillStyle = theme.background;
  ctx.fillRect(0, 0, CANVAS_WIDTH, canvasHeight);
  if (theme.themed) {
    // soft coloured glows like on the poster: pink bottom-left, orange bottom-right, purple top-right
    const glow = (x, y, r, color) => {
      const g = ctx.createRadialGradient(x, y, 0, x, y, r);
      g.addColorStop(0, color);
      g.addColorStop(1, 'rgba(0,0,0,0)');
      ctx.fillStyle = g;
      ctx.fillRect(0, 0, CANVAS_WIDTH, canvasHeight);
    };
    glow(0, canvasHeight, CANVAS_WIDTH * 0.75, 'rgba(243, 36, 212, 0.55)');
    glow(CANVAS_WIDTH, canvasHeight, CANVAS_WIDTH * 0.6, 'rgba(253, 122, 49, 0.45)');
    glow(CANVAS_WIDTH, bannerHeight, CANVAS_WIDTH * 0.6, 'rgba(101, 74, 220, 0.45)');
    if (logo) {
      ctx.drawImage(logo, 0, 0, CANVAS_WIDTH, bannerHeight);
    }
  }

  // draw header text at top-left
  ctx.font = HEADER_FONT;
  ctx.fillStyle = HEADER_COLOR;
  ctx.textBaseline = 'top';
  const headerX = PADDING;
  const headerY = theme.themed ? bannerHeight + 20 : PADDING + 30; // below the banner / moved down by 30px
  ctx.fillText('Мой ТОП лист', headerX, headerY);
  if (theme.themed && !bannerHeight && theme.festival) {
    // no poster: festival name under the header
    ctx.font = '600 20px "Arial"';
    ctx.fillText(theme.festival, headerX, headerY + 44);
  }

  // draw logo top-right if available (themed: the banner was drawn with the background)
  if (logo && !theme.themed) {
    const logoX = CANVAS_WIDTH - LOGO_WIDTH;
    const logoY = 0;
    ctx.drawImage(logo, logoX, logoY, LOGO_WIDTH, LOGO_HEIGHT);
  }

  // draw rows
  let cursorY = PADDING + headerTopArea;
  for (const row of rows) {
    const leftBox = row[0];
    const rightBox = row[1];

    // left position for the row start
    const leftX = PADDING;

    // draw left box
    drawSessionBox(ctx, leftX, cursorY, leftBox.width, leftBox.height, leftBox);
    // draw right box if exists
    if (rightBox) {
      const rightX = leftX + leftBox.width + GAP_BETWEEN_RECTS;
      drawSessionBox(ctx, rightX, cursorY, rightBox.width, rightBox.height, rightBox);
    }

    cursorY += Math.max(leftBox.height, (rightBox ? rightBox.height : 0)) + VERTICAL_GAP_BETWEEN_ROWS;
  }

  // export to jpeg
  const dataUrl = canvas.toDataURL('image/jpeg', 0.92);
  const link = document.createElement('a');
  link.href = dataUrl;
  link.download = 'bookmarks.jpg';
  link.click();

  // utility: draw rounded rectangle and text inside
  function drawSessionBox(ctx, x, y, width, height, box) {
    // rounded white rectangle
    // themed: filled with the session-type colour like the programme cards, white text; otherwise white card
    const filled = theme.themed && box.color;
    roundRect(ctx, x, y, width, height, RECT_RADIUS, true, false, filled ? box.color : '#ffffff');

    // prepare inner text area
    const innerX = x + RECT_PADDING_X;
    let innerY = y + RECT_PADDING_Y;

    // draw title lines
    ctx.fillStyle = filled ? '#ffffff' : '#000000';
    ctx.textBaseline = 'top';
    ctx.font = `${box.titleFontSize}px Arial`;
    const titleLines = box.titleLines;
    for (let i = 0; i < titleLines.length; i++) {
      ctx.fillText(titleLines[i], innerX, innerY);
      innerY += box.titleLineHeight;
    }

    // small gap between title and presenters
    innerY += 6;

    // draw presenter lines
    ctx.font = `${box.presFontSize}px Arial`;
    ctx.fillStyle = filled ? 'rgba(255, 255, 255, 0.85)' : '#333333';
    const presLines = box.presLines;
    for (let i = 0; i < presLines.length; i++) {
      ctx.fillText(presLines[i], innerX, innerY);
      innerY += box.presLineHeight;
    }
  }
}

// Helper: load image
function loadImage(src) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      console.log('Logo image loaded successfully:', src);
      resolve(img);
    };
    img.onerror = (err) => {
      console.error('Failed to load image:', src, err);
      reject(err);
    };
    img.src = src;
  });
}

// Helper: compute minimal box width & height for session
// If forcedWidth provided, compute layout using that width.
function computeBoxSizeForSession(mctx, session, availableRowWidth, forcedWidth = null) {
  const maxRectWidth = forcedWidth || Math.floor((availableRowWidth - GAP_BETWEEN_RECTS) * 0.9);
  // We'll search width from min to max to find minimal width that fits with constraints
  const MIN_WIDTH = 120;
  const MAX_WIDTH = forcedWidth || Math.min(maxRectWidth, availableRowWidth);

  // function to test layout at specific width: returns object or null if cannot fit
  function testAt(width) {
    // title font: try decreasing sizes until min or fits lines
    let titleSize = TITLE_BASE_SIZE;
    let presSize = PRES_BASE_SIZE;
    let titleLines = [];
    let presLines = [];
    let titleLineHeight, presLineHeight;

    // Try to fit by reducing title font first, then presenter font
    for (let t = titleSize; t >= TITLE_MIN_SIZE; t--) {
      // set font and wrap title
      mctx.font = `${t}px Arial`;
      titleLineHeight = Math.ceil(t * 1.2);
      titleLines = wrapTextLines(mctx, session.title, width - 2 * RECT_PADDING_X, MAX_LINES_TITLE);
      // if wrapped lines exceed allowed lines with current font, reduce font
      if (titleLines.length <= MAX_LINES_TITLE) {
        titleSize = t;
        break;
      }
      if (t === TITLE_MIN_SIZE) {
        // Continue reducing font size below minimum until text fits
        titleSize = t;
        while (titleLines.length > MAX_LINES_TITLE && titleSize > 6) {
          titleSize--;
          mctx.font = `${titleSize}px Arial`;
          titleLineHeight = Math.ceil(titleSize * 1.2);
          titleLines = wrapTextLines(mctx, session.title, width - 2 * RECT_PADDING_X, MAX_LINES_TITLE);
        }
        // If still doesn't fit, truncate
        if (titleLines.length > MAX_LINES_TITLE) {
          titleLines = titleLines.slice(0, MAX_LINES_TITLE);
        }
      }
    }

    // Presenter lines: similar strategy
    for (let p = presSize; p >= PRES_MIN_SIZE; p--) {
      mctx.font = `${p}px Arial`;
      presLineHeight = Math.ceil(p * 1.2);
      presLines = wrapTextLines(mctx, session.presenters || '', width - 2 * RECT_PADDING_X, MAX_LINES_PRESENTERS);
      if (presLines.length <= MAX_LINES_PRESENTERS) {
        presSize = p;
        break;
      }
      if (p === PRES_MIN_SIZE) {
        presSize = p;
        // If still doesn't fit, truncate
        if (presLines.length > MAX_LINES_PRESENTERS) {
          presLines = presLines.slice(0, MAX_LINES_PRESENTERS);
        }
      }
        }


    // Now compute required height
    const titleHeight = titleLines.length * titleLineHeight;
    const presHeight = presLines.length * presLineHeight;
    const totalInnerHeight = titleHeight + 6 + presHeight; // 6 px gap
    const boxHeight = totalInnerHeight + 2 * RECT_PADDING_Y;

    return {
      width,
      height: boxHeight,
      titleFontSize: titleSize,
      presFontSize: presSize,
      titleLines,
      presLines,
      titleLineHeight,
      presLineHeight,
      color: session.color || ''
    };
  }

  // If forced width provided, just compute for that width
  if (forcedWidth) {
    return testAt(forcedWidth);
  }

  // Otherwise attempt to find minimal viable width: try widths from MIN to MAX
  for (let w = MIN_WIDTH; w <= MAX_WIDTH; w += 4) {
    const res = testAt(w);
    // Prefer small widths: return first that yields reasonable lines (<= max lines)
    if (res) return res;
  }
  // fallback: compute at MAX_WIDTH
  return testAt(MAX_WIDTH);
}

// Helper: wrap text into lines limited by maxWidth and return array of lines
function wrapTextLines(ctx, text, maxWidth, maxLines) {
  if (!text) return [];
  const words = text.split(/\s+/);
  const lines = [];
  let current = words[0] || '';
  for (let i = 1; i < words.length; i++) {
    const word = words[i];
    const test = current + ' ' + word;
    const metrics = ctx.measureText(test);
    if (metrics.width > maxWidth) {
      lines.push(current);
      current = word;
    } else {
      current = test;
    }
  }
  lines.push(current);
  // Return all lines (don't truncate here - let the caller handle it)
  return lines;
}

// draw rounded rectangle helper: fill (fillColor) optional
function roundRect(ctx, x, y, w, h, r, fill = true, stroke = false, fillColor = '#fff') {
  const radius = Math.min(r, w / 2, h / 2);
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.arcTo(x + w, y, x + w, y + h, radius);
  ctx.arcTo(x + w, y + h, x, y + h, radius);
  ctx.arcTo(x, y + h, x, y, radius);
  ctx.arcTo(x, y, x + w, y, radius);
  ctx.closePath();
  if (fill) {
    ctx.fillStyle = fillColor;
    ctx.fill();
  }
  if (stroke) {
    ctx.stroke();
  }
}
